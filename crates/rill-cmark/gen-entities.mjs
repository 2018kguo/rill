// Generates rill-cmark's named character references from micromark's own table
// (character-entities, via decode-named-character-reference), packed as two strings
// and their end offsets so the wasm carries no per-entry pointers.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const main = require.resolve("character-entities", {
  paths: [require.resolve("decode-named-character-reference")],
});
const { characterEntities } = await import(main);
const { version } = JSON.parse(
  readFileSync(new URL("package.json", `file://${main}`), "utf8")
);

const names = Object.keys(characterEntities).sort((a, b) =>
  Buffer.compare(Buffer.from(a), Buffer.from(b))
);
const escape = (s) =>
  [...s].map((c) => `\\u{${c.codePointAt(0).toString(16).toUpperCase().padStart(4, "0")}}`).join("");

function packed(name, parts, encode) {
  let end = 0;
  const ends = parts.map((part) => (end += Buffer.byteLength(part)));
  if (end > 0xffff) throw new Error(`${name} exceeds u16 offsets`);
  const lines = [];
  for (let i = 0; i < parts.length; i += 12) {
    lines.push(`    "${parts.slice(i, i + 12).map(encode).join("")}",`);
  }
  const offsets = [];
  for (let i = 0; i < ends.length; i += 16) {
    offsets.push(`    ${ends.slice(i, i + 16).join(", ")},`);
  }
  return (
    `#[rustfmt::skip]\nstatic ${name}: &str = concat!(\n${lines.join("\n")}\n);\n\n` +
    `#[rustfmt::skip]\nstatic ${name}_ENDS: [u16; ${ends.length}] = [\n${offsets.join("\n")}\n];\n\n`
  );
}

let out = `// @generated by gen-entities.mjs from character-entities ${version}, micromark's table.
// Do not edit by hand.

//! Expansions of HTML5 entities

`;
out += packed("NAMES", names, (s) => s);
out += packed("VALUES", names.map((name) => characterEntities[name]), escape);
out += `fn entry(packed: &'static str, ends: &[u16], ix: usize) -> &'static str {
    let start = if ix == 0 { 0 } else { ends[ix - 1] as usize };
    &packed[start..ends[ix] as usize]
}

pub(crate) fn get_entity(bytes: &[u8]) -> Option<&'static str> {
    let (mut lo, mut hi) = (0, NAMES_ENDS.len());
    while lo < hi {
        let mid = (lo + hi) / 2;
        match entry(NAMES, &NAMES_ENDS, mid).as_bytes().cmp(bytes) {
            std::cmp::Ordering::Less => lo = mid + 1,
            std::cmp::Ordering::Greater => hi = mid,
            std::cmp::Ordering::Equal => return Some(entry(VALUES, &VALUES_ENDS, mid)),
        }
    }
    None
}
`;
writeFileSync(new URL("./src/entities.rs", import.meta.url), out);
console.log(`wrote entities.rs (${names.length} entities)`);
