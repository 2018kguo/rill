// Generates rill-cmark's Unicode classes from the JavaScript engine's own
// regular expressions, so native classification equals micromark's in this runtime.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
// remark-cjk-friendly's own East Asian Width dependency.
const { eastAsianWidthType } = await import(
  require.resolve("get-east-asian-width", {
    paths: [require.resolve("micromark-extension-cjk-friendly-util")],
  })
);
// micromark-extension-cjk-friendly-util `cjkOrIvs`, verbatim.
function cjkOrIvs(uc) {
  if (!uc || uc < 4352) return false;
  switch (eastAsianWidthType(uc)) {
    case "fullwidth":
    case "halfwidth":
      return true;
    case "wide":
      return !/^\p{Emoji_Presentation}/u.test(String.fromCodePoint(uc));
    case "narrow":
      return false;
    case "ambiguous":
      return 917760 <= uc && uc <= 917999 ? null : false;
    case "neutral":
      return /^\p{sc=Hangul}/u.test(String.fromCodePoint(uc));
  }
}

const test = (pattern) => (cp) => pattern.test(String.fromCodePoint(cp));
const classes = {
  // `/\p{P}|\p{S}/u` by code point. Core micromark reads UTF-16 code units, so callers
  // treat supplementary characters as neither punctuation nor whitespace there.
  PUNCTUATION_OR_SYMBOL: test(/\p{P}|\p{S}/u),
  // micromark-util-character `unicodeWhitespace` (JavaScript `\s`)
  WHITESPACE: test(/\s/u),
  // remark-cjk-friendly: CJK characters, and ideographic variation selectors.
  CJK: (cp) => cjkOrIvs(cp) === true,
  IVS: (cp) => cjkOrIvs(cp) === null,
};
let out = `// @generated by scripts/gen-unicode-tables.mjs on Node ${process.versions.node} (Unicode ${process.versions.unicode}).\n// Do not edit by hand.\n\n`;
for (const [name, pattern] of Object.entries(classes)) {
  const ranges = [];
  let start = -1;
  for (let cp = 0; cp <= 0x10ffff; cp += 1) {
    const inside = cp >= 0xd800 && cp <= 0xdfff ? false : pattern(cp);
    if (inside && start < 0) start = cp;
    if (!inside && start >= 0) {
      ranges.push([start, cp - 1]);
      start = -1;
    }
  }
  if (start >= 0) ranges.push([start, 0x10ffff]);
  out += `pub(crate) static ${name}: &[(u32, u32)] = &[\n${ranges.map(([a, b]) => `    (0x${a.toString(16)}, 0x${b.toString(16)}),`).join("\n")}\n];\n\n`;
}
out += `pub(crate) fn in_table(table: &[(u32, u32)], c: char) -> bool {
    let cp = c as u32;
    table
        .binary_search_by(|&(start, end)| {
            if end < cp {
                std::cmp::Ordering::Less
            } else if start > cp {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}
`;
writeFileSync(
  new URL("./src/unicode_tables.rs", import.meta.url),
  out
);
console.log("wrote unicode_tables.rs");
