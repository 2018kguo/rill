// Generates crates/rill-highlight/src/regex/unicode_tables.rs from the running V8, so the
// Rust regex engine sees exactly the Unicode data that V8's RegExp uses:
//   - code point ranges of each property escape the translated grammars use
//   - simple case folding classes as V8 applies them under the `i` flag (u/v mode)
import { writeFileSync } from 'node:fs';

const generalCategories = ['L', 'LC', 'Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'M', 'Mn', 'Mc', 'Me', 'N', 'Nd', 'Nl', 'No',
  'P', 'Pc', 'Pd', 'Ps', 'Pe', 'Pi', 'Pf', 'Po', 'S', 'Sm', 'Sc', 'Sk', 'So', 'Z', 'Zs', 'Zl', 'Zp',
  'C', 'Cc', 'Cf', 'Cs', 'Co', 'Cn'];
// The binary properties and scripts that oniguruma-to-es output for Shiki's bundled grammars uses.
// A pattern naming any other property fails to compile in Rust and its language falls back.
const binaryProperties = ['White_Space', 'Alphabetic', 'ASCII_Hex_Digit', 'Uppercase', 'Lowercase', 'Any', 'ASCII',
  'XID_Start', 'XID_Continue'];
const scripts = ['Greek', 'Han', 'Hangul', 'Katakana', 'Hiragana'];

function rangesOf(source) {
  const ranges = [];
  const push = (lo, hi) => { const last = ranges.at(-1); if (last && last[1] + 1 === lo) last[1] = hi; else ranges.push([lo, hi]); };
  const test = new RegExp(`^${source}$`, 'v');
  for (let cp = 0; cp < 0x110000; cp++) {
    if (test.test(String.fromCodePoint(cp))) push(cp, cp);
  }
  return ranges;
}

const tables = [];
const aliases = [];
for (const gc of generalCategories) tables.push([`gc=${gc}`, rangesOf(`\\p{gc=${gc}}`)]);
for (const p of binaryProperties) tables.push([p, rangesOf(`\\p{${p}}`)]);
for (const s of scripts) { tables.push([`sc=${s}`, rangesOf(`\\p{sc=${s}}`)]); tables.push([`scx=${s}`, rangesOf(`\\p{scx=${s}}`)]); }

// Case folding classes as V8 matches them: two code points are equivalent when
// /[a]/iv matches b. Candidates are the code points that take part in case mapping.
const candidates = [];
const cased = /[\p{Changes_When_Casemapped}\p{Changes_When_Casefolded}\p{Changes_When_Lowercased}\p{Changes_When_Uppercased}\p{Changes_When_Titlecased}]/v;
for (let cp = 0; cp < 0x110000; cp++) if (cased.test(String.fromCodePoint(cp))) candidates.push(cp);
// Fold targets that are not casemapped themselves.
const inCandidates = new Set(candidates);
const representative = new Map();
for (const cp of candidates) {
  if (representative.has(cp)) continue;
  const re = new RegExp(`^[\\u{${cp.toString(16)}}]$`, 'iv');
  const cls = [cp];
  for (const other of candidates) if (other !== cp && re.test(String.fromCodePoint(other))) cls.push(other);
  // Check the class is closed: every member matches the same set.
  const min = Math.min(...cls);
  for (const member of cls) {
    if (representative.has(member) && representative.get(member) !== min) throw new Error(`not an equivalence at ${member}`);
    representative.set(member, min);
  }
}
// Members outside the candidate set would break the closure; verify on all code points
// for a sample of classes (all BMP).
for (const [cp, rep] of representative) if (!inCandidates.has(rep)) throw new Error('rep outside');
const folds = [...representative].filter(([cp, rep]) => cp !== rep).sort((a, b) => a[0] - b[0]);
// Exhaustive closure check: no code point outside the candidates matches any non-trivial class.
const nonTrivial = new RegExp(`[${[...new Set(folds.flatMap(([a, b]) => [a, b]))].map((c) => `\\u{${c.toString(16)}}`).join('')}]`, 'iv');
for (let cp = 0; cp < 0x110000; cp++) {
  if (!representative.has(cp) && nonTrivial.test(String.fromCodePoint(cp))) {
    if (!(cp >= 0xd800 && cp <= 0xdfff)) throw new Error(`code point ${cp.toString(16)} folds but is not a candidate`);
  }
}

const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
let out = `// @generated by highlight/scripts/gen-unicode-tables.mjs from V8 ${process.versions.v8}\n`;
out += `// (Unicode ${process.versions.unicode}). Do not edit.\n\n`;
out += `/// Unicode version of the V8 the tables were taken from.\npub const UNICODE_VERSION: &str = "${process.versions.unicode}";\n\n`;
out += `/// Property tables as inclusive code point ranges, keyed by canonical name.\n`;
out += `pub static PROPERTIES: &[(&str, &[(u32, u32)])] = &[\n`;
for (const [name, ranges] of tables) out += `    ("${name}", &[${ranges.map(([a, b]) => `(${hex(a)}, ${hex(b)})`).join(', ')}]),\n`;
out += `];\n\n`;
out += `/// Simple case folding as V8 applies it: (code point, smallest code point of its class),\n/// sorted, for every code point whose class representative is not itself.\n`;
out += `pub static CASE_FOLDS: &[(u32, u32)] = &[\n${folds.map(([a, b]) => `    (${hex(a)}, ${hex(b)}),`).join('\n')}\n];\n`;
writeFileSync(new URL('../../crates/rill-highlight/src/regex/unicode_tables.rs', import.meta.url), out);
console.log(`${tables.length} property tables, ${folds.length} folds`);
