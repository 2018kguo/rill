// Packages rill-highlight's data (highlight/dist, from highlight/scripts/build-grammars.mjs
// and build-wasm.sh) for the JavaScript package: js/highlight/ holds one module per
// grammar and theme (a string of its JSON), an index that imports each on demand (so
// every bundler splits them into chunks loaded only when a block uses them), the
// language table, rill-highlight's core and its Streamdown code plugin; the wasm goes
// to js/wasm/.
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const repo = new URL("..", import.meta.url).pathname;
const dist = join(repo, "highlight/dist");
const out = join(repo, "js/highlight");
rmSync(out, { recursive: true, force: true });
for (const directory of ["grammars", "themes"]) mkdirSync(join(out, directory), { recursive: true });

const entries = (directory) => {
  const names = [];
  for (const file of readdirSync(join(dist, directory)).sort()) {
    const name = file.replace(/\.json$/, "");
    const text = readFileSync(join(dist, directory, file), "utf8");
    writeFileSync(join(out, directory, `${name}.js`), `export default ${JSON.stringify(text)};\n`);
    names.push(name);
  }
  return names;
};
const grammars = entries("grammars");
const themes = entries("themes");
const table = (directory, names) =>
  `{\n${names.map((name) => `  ${JSON.stringify(name)}: () => import("./${directory}/${name}.js"),`).join("\n")}\n}`;
writeFileSync(
  join(out, "index.js"),
  `// @generated by scripts/build-highlight-data.mjs. Do not edit.
export { default as languages } from "./languages.js";
export const grammars = ${table("grammars", grammars)};
export const themes = ${table("themes", themes)};
`
);
writeFileSync(
  join(out, "index.d.ts"),
  `type Loader = () => Promise<{ default: string }>;
export declare const languages: Record<string, { name: string; aliases?: string[]; grammars: string[] }>;
export declare const grammars: Record<string, Loader>;
export declare const themes: Record<string, Loader>;
`
);
writeFileSync(
  join(out, "languages.js"),
  `export default ${readFileSync(join(dist, "languages.json"), "utf8").trim()};\n`
);
for (const file of ["core.js", "code-plugin.js"]) {
  copyFileSync(join(repo, "highlight/js", file), join(out, file));
}
writeFileSync(
  join(out, "core.d.ts"),
  `export declare function createHighlightCore(options: {
  wasm: BufferSource | URL | Response | WebAssembly.Module;
  data: {
    languages: Record<string, unknown>;
    grammar(name: string): Promise<string> | string;
    theme(name: string): Promise<string> | string;
  };
}): Promise<unknown>;
`
);
writeFileSync(
  join(out, "code-plugin.d.ts"),
  `export declare function createCodePlugin(options: { core: unknown; themes?: [string, string] }): unknown;
`
);
mkdirSync(join(repo, "js/wasm"), { recursive: true });
copyFileSync(join(dist, "rill_highlight.wasm"), join(repo, "js/wasm/rill_highlight.wasm"));
console.log(`js/highlight: ${grammars.length} grammars, ${themes.length} themes`);
