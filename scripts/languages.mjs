// Writes js/src/languages.ts: rill-highlight's languages and their aliases (from its
// manifest), which `@2018kguo/rill/code` answers `supportsLanguage` from without loading
// the manifest. js/test/code.test.ts fails when the two differ.
//
//   node scripts/languages.mjs
import { writeFileSync } from "node:fs";

const { default: manifest } = await import("@2018kguo/rill-highlight/dist/manifest.js");
const entries = Object.entries(manifest.languages).map(([id, entry]) => [id, ...entry.aliases].join(" "));
writeFileSync(
  new URL("../js/src/languages.ts", import.meta.url),
  `// Generated by scripts/languages.mjs from @2018kguo/rill-highlight's manifest: each\n` +
    `// language, then its aliases, space-separated.\n` +
    `export const LANGUAGES = ${JSON.stringify(entries.join(","))};\n`
);
